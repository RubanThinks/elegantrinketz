/**
 * Returns the list of districts for a given state name (case-insensitive match).
 */
export function getDistrictsForState(stateName: string): string[] {
  if (!stateName) return [];
  const trimmed = stateName.trim();
  // Exact lookup
  if (INDIAN_DISTRICTS_BY_STATE[trimmed]) {
    return INDIAN_DISTRICTS_BY_STATE[trimmed];
  }
  // Case-insensitive lookup
  const foundKey = Object.keys(INDIAN_DISTRICTS_BY_STATE).find(
    (k) => k.toLowerCase() === trimmed.toLowerCase()
  );
  if (foundKey) {
    return INDIAN_DISTRICTS_BY_STATE[foundKey];
  }
  return [];
}
